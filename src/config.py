import argparse
import os
import random
import sys
from pathlib import Path
from typing import Any, Dict

import numpy as np
import torch
import yaml

# ??????????? ??????? ????? ??????? ? sys.path
PROJECT_ROOT = Path(__file__).resolve().parent.parent
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))


class ConfigDict(dict):
    """
    ??????? ? ?????????? ????????? ??????? ? ?????:
    cfg.model.dropout_rate ?????? cfg['model']['dropout_rate'].
    """
    def __getattr__(self, name: str) -> Any:
        try:
            val = self[name]
            if isinstance(val, dict) and not isinstance(val, ConfigDict):
                val = ConfigDict(val)
                self[name] = val
            return val
        except KeyError:
            raise AttributeError(f"???????????? ?? ???????? ?????????: '{name}'")

    def __setattr__(self, name: str, value: Any) -> None:
        self[name] = value


def set_seed(seed: int = 42) -> None:
    """
    ????????? ?????????? ????????? ????? ?? ???? ??????????? ??? ?????????????????.
    ??? ??????????????? ?????????? ??? ??????? ?????? (IMRAD).
    """
    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)
    torch.cuda.manual_seed(seed)
    torch.cuda.manual_seed_all(seed)
    torch.backends.cudnn.deterministic = True
    torch.backends.cudnn.benchmark = False


def get_device(device_setting: str = "auto") -> torch.device:
    """
    ????????????? ?????????? ??????????? GPU (CUDA).
    ???? ??????? 'auto': ?????????? cuda ??? ???????, ????? cpu.
    """
    if device_setting == "auto":
        return torch.device("cuda" if torch.cuda.is_available() else "cpu")
    return torch.device(device_setting)


def load_config(env: str = None, config_path: str = None) -> ConfigDict:
    """
    ????????? YAML-?????? ??? ?????????? ????????? ??? Kaggle.
    - env: 'local' ??? 'kaggle'
    - config_path: ????? ???? ? YAML ?????
    """
    if config_path is None:
        if env is None:
            # ???????????????: ???? ?? ???????? ?????? Kaggle
            env = "kaggle" if os.path.exists("/kaggle/input") else "local"
        
        project_root = Path(__file__).resolve().parent.parent
        config_path = str(project_root / "configs" / f"{env}.yaml")

    if not os.path.exists(config_path):
        raise FileNotFoundError(f"???? ???????????? ?? ??????: {config_path}")

    with open(config_path, "r", encoding="utf-8") as f:
        raw_cfg = yaml.safe_load(f)

    cfg = ConfigDict(raw_cfg)

    # ??????? ???????? ????? outputs
    output_dir = Path(cfg.output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    # ??????????? ???? ? ??????????
    cfg.paths = ConfigDict({
        "train_features_h5": str(output_dir / "train_img_features.h5"),
        "val_features_h5": str(output_dir / "val_img_features.h5"),
        "vocab_json": str(output_dir / "vocab.json"),
        "best_model_pth": str(output_dir / "best_model.pth"),
        "best_question_only_pth": str(output_dir / "best_question_only_model.pth"),
        "predictions_csv": str(output_dir / "predictions.csv"),
        "metrics_table_csv": str(output_dir / "metrics_table.csv"),
        "learning_curves_png": str(output_dir / "learning_curves.png"),
        "metrics_history_json": str(output_dir / "metrics_history.json")
    })

    # ?????????? ???????? ??????????
    actual_device = get_device(cfg.get("device", "auto"))
    cfg.resolved_device = actual_device

    # ????????? ??????????????? seed
    set_seed(cfg.get("seed", 42))

    return cfg


def parse_args_and_get_config() -> ConfigDict:
    """
    ?????? ????????? ????????? ?????? (--env ??? --config).
    """
    parser = argparse.ArgumentParser(description="VQA Baseline Pipeline")
    parser.add_argument(
        "--env",
        type=str,
        choices=["local", "kaggle"],
        default=None,
        help="??????? ?????????: local ??? kaggle"
    )
    parser.add_argument(
        "--config",
        type=str,
        default=None,
        help="?????? ???? ? ????????????????? YAML ?????"
    )
    args, _ = parser.parse_known_args()
    return load_config(env=args.env, config_path=args.config)


if __name__ == "__main__":
    config = parse_args_and_get_config()
    print("=== Config Test ===")
    print(f"Env: {config.env}")
    print(f"Device: {config.resolved_device}")
    print(f"Output: {config.output_dir}")
    print(f"Train features: {config.paths.train_features_h5}")
